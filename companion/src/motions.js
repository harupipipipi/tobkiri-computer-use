const ease = (u) => u * u * u * (u * (u * 6 - 15) + 10);
const mix = (a, b, u) => a + (b - a) * u;
export function extraPose(action, seconds) {
  const c = clips[action];
  if (!c) return null;
  const phase = (((seconds / c.duration) % 1) + 1) % 1;
  const i = Math.max(0, c.frames.findIndex((frame) => frame.at > phase) - 1);
  const a = c.frames[i],
    b = c.frames[i + 1],
    u = ease((phase - a.at) / (b.at - a.at));
  const angle = mix(a.turn, b.turn, u),
    cos = Math.cos(angle),
    sin = Math.sin(angle);
  const ox = mix(a.offset[0], b.offset[0], u),
    oy = mix(a.offset[1], b.offset[1], u);
  return a.pose.map((v, j) => {
    const x = mix(v[0], b.pose[j][0], u),
      y = mix(v[1], b.pose[j][1], u);
    if (j === 9) return [x, y];
    // Rotate the rig around its pelvis; the round head is drawn independently.
    return [x * cos - (y + 43) * sin + ox, x * sin + (y + 43) * cos - 43 + oy];
  });
}
const quietPhrases = [
  ["idle", 6],
  ["peek", 6],
  ["hip_pop", 2.1],
  ["idle", 4],
  ["stretch", 6],
  ["look_around", 3.6],
  ["idle", 4],
  ["bounce", 1.8],
  ["shrug", 2.4],
  ["wait", 4],
  ["yawn", 3.2],
  ["sit", 6],
  ["sleep", 8],
];
const quietDuration = quietPhrases.reduce(
  (sum, [, seconds]) => sum + seconds,
  0,
);
export function idleMotion(seconds) {
  let t = seconds % quietDuration;
  for (const [action, duration] of quietPhrases) {
    if (t < duration) return action;
    t -= duration;
  }
  return "idle";
}
